const { chromium } = require('playwright');
const BASE = 'http://localhost:8766/'; const errs = []; const log = (...a) => console.log(...a);
const d = new Date().toISOString().slice(0, 10);
(async () => {
  const b = await chromium.launch();
  const mk = async () => {
    const ctx = await b.newContext({ viewport: { width: 1000, height: 800 }, locale: 'de-DE' });
    await ctx.addInitScript(() => { localStorage.setItem('lp.nointro', 'true'); localStorage.setItem('lp.autoPing', 'false'); });
    await ctx.route(/tile\.openstreetmap|overpass|open-meteo|osrm|nominatim/, r => r.fulfill({ status: 404, body: '' }));
    const p = await ctx.newPage(); p.on('dialog', x => x.accept());
    p.on('pageerror', e => errs.push('pageerror ' + e.message)); p.on('console', m => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errs.push(m.text()); });
    return p;
  };
  const login = async (p, l, pw) => { await p.goto(BASE); await p.fill('[name=login]', l); await p.fill('[name=password]', pw); await p.click('form[data-form=login] button'); await p.waitForTimeout(2500);
    while (await p.$('.stamp-pop')) { await p.click('.stamp-pop [data-sp]'); await p.waitForTimeout(150); } };
  const t = await mk(); await login(t, 'tobi', 'segeln1');
  const crew = await t.evaluate(() => JSON.parse(localStorage.getItem('lp.crew')));
  const post = (p, a, body) => p.evaluate(([a, body]) => fetch('api/?a=' + a, { method: 'POST', headers: { 'X-Lammping': '1', 'Content-Type': 'application/json' }, body: JSON.stringify(body) }).then(r => r.json()), [a, body]);
  await post(t, 'user-save', { name: 'Franz', login: 'franz76', password: 'geheim1', canCash: true, isAdmin: false, canFound: true });
  await post(t, 'push', { crew, changes: [{ coll: 'trips', id: 'go76', data: { id: 'go76', name: 'Norwegen', start: d } }] });
  const f = await mk(); await f.goto(BASE); await f.fill('[name=login]', 'franz76'); await f.fill('[name=password]', 'geheim1'); await f.click('form[data-form=login] button'); await f.waitForTimeout(2000);
  const fc = await post(f, 'crew-save', { name: 'Familie Franz' });
  await f.reload(); await f.waitForTimeout(6000);
  await post(f, 'push', { crew: (await f.evaluate(() => JSON.parse(localStorage.getItem('lp.crew')))), changes: [{ coll: 'trips', id: 'fz76', data: { id: 'fz76', name: 'Zuhause', start: d } }] });
  await f.reload(); await f.waitForTimeout(6000); await f.evaluate(() => { location.hash = '#/tagebuch'; }); await f.waitForTimeout(1200);
  log('1 Franz Zeile:', await f.$$eval('.crew-row', xs => xs.map(x => x.innerText.replace(/\s+/g, ' ')).join(' | ')));
  await f.click('.crew-row [data-action=mr-op][data-op=request]'); await f.waitForTimeout(1500);
  await f.evaluate(() => { location.hash = '#/tagebuch'; }); await f.waitForTimeout(1000);
  log('2 Franz Zeile danach:', await f.$$eval('.crew-row', xs => xs.map(x => x.innerText.replace(/\s+/g, ' ')).join(' | ')));
  await t.reload(); await t.waitForTimeout(6000);
  await t.evaluate(() => { location.hash = '#/tagebuch'; }); await t.waitForTimeout(1200);
  log('3 Tobi Zeile:', await t.$$eval('.crew-row', xs => xs.map(x => x.innerText.replace(/\s+/g, ' ')).join(' | ')));
  await t.click('.crew-row[data-action=cr-goto]'); await t.waitForTimeout(1500);
  log('3 Tobi Seite:', await t.$eval('#view', x => x.innerText.replace(/\s+/g, ' ').slice(0, 300)));
  await t.click('[data-action=mr-op][data-op=accept]'); await t.waitForTimeout(1200);
  await t.evaluate(() => { location.hash = '#/tagebuch'; }); await t.waitForTimeout(1000);
  log('4 Tobi Zeile danach:', await t.$$eval('.crew-row', xs => xs.map(x => x.innerText.replace(/\s+/g, ' ')).join(' | ')));
  await t.evaluate(() => { location.hash = '#/einstellungen'; }); await t.waitForTimeout(2000);
  log('5 Mitteilungen:', await t.$eval('#pushBody', x => x.innerText.replace(/\s+/g, ' ').slice(0, 300)).catch(() => '-'));
  log('Fehler:', errs.length ? errs.join('\n') : 'keine');
  await b.close();
})();
